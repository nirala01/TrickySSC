    texts = [Q_HI[n][x] for x in "ABCD"]
    N = lambda s: ud.normalize('NFC', s)
    full = {}
    for k, v in opt.items():
        hits = [t for t in texts if N(t) == N(k)] or [t for t in texts if N(t).startswith(N(k))]
        assert len(hits) == 1, (n, k, hits)
        full[hits[0]] = v
